const STRINGS = { en, 'zh-TW': zh };
export const LANGS = ['en', 'zh-TW'];
let current = 'en';

/** Any Chinese variant (zh, zh-CN, zh-HK, zh-Hant…) → zh-TW; every other language → English. */
export function detectLang() {
  const primary = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  return String(primary).toLowerCase().startsWith('zh') ? 'zh-TW' : 'en';
}

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current;
  return current;
}

export const getLang = () => current;

export function t(key, vars) {
  let s = STRINGS[current][key];
  if (s === undefined) s = en[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

const ZH_NUM = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
/** Numbers 1–9 as Chinese numerals in zh-TW (used for "二對三"), digits otherwise. */
export function numWord(n) {
  return current === 'zh-TW' && n >= 0 && n < 10 ? ZH_NUM[n] : String(n);
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const s = t(el.dataset.i18nTitle);
    el.title = s;
    if (!el.hasAttribute('aria-label') || el.dataset.i18nTitleAria !== 'no') el.setAttribute('aria-label', s);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.title = t('app.title');
}
